package Homework;

//! Q7. Print Counting from 1 to N

public class ques6 {

    public static void main(String[] args) {
        int N = 10; // You can change this value to print counting up to a different number

        System.out.println("Counting from 1 to " + N + ":");
        for (int i = 1; i <= N; i++) {
            System.out.println(i + " ");
        }
    }
}
